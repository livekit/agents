//! `_scheduling_task` and its queue: the [`SchedulingTask`], the speech vocabulary, and the
//! driver's scheduling, authorization, pause and `_current_speech` queries.

use crate::agent_session::cycle::Cycle;
use crate::agent_session::Driver;
use crate::events::SessionEvent;
use crate::speech_handle::{INTERRUPTION_TIMEOUT, SpeechHandle};
use crate::trace::{CloseAct, CloseStep, InterruptCause, InterruptStep, SpeechStep, TurnStep};
use lk_agents_abi::Ts;
use lk_agents_abi::voice::events::AgentState;
use std::collections::{BTreeMap, VecDeque};
use std::sync::Arc;
use std::time::Duration;

/// Priority for messages that should be played after all other messages in the queue.
pub const SPEECH_PRIORITY_LOW: i32 = 0;

/// Every speech generated by the VoiceAgent defaults to this priority.
pub const SPEECH_PRIORITY_NORMAL: i32 = 5;

/// Priority for important messages that should be played before others.
pub const SPEECH_PRIORITY_HIGH: i32 = 10;

const HANDOFF: &str = "a handoff resumed scheduling before the drain completed";

const CLOSING: &str = "the session is closing";

use scheduling_task::{Finished, NextSpeech, Requeue, SchedulingPass};
pub use scheduling_task::{SchedulingTask, Status};

/// The scheduling state, behind its methods: the driver reaches none of its fields.
mod scheduling_task {
    use super::*;

    /// `_scheduling_paused`: new speech refused (tool replies excepted), queued speech still plays,
    /// every caller answered when nothing is outstanding.
    #[derive(Debug)]
    struct Pause {
        cause: PauseCause,
        acks: Vec<tokio::sync::oneshot::Sender<()>>,
    }

    /// Where `_scheduling_task`'s loop is: waiting for `_speech_q`, sleeping out
    /// `min_consecutive_speech_delay`, waiting for `_authorization_allowed`, or with a
    /// `_current_speech`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    enum SchedulingStep {
        Idle,
        /// `min_consecutive_speech_delay` still owed: a deadline, not a sleep. `next` is `None`
        /// once that candidate finished early; the gap still stands.
        Delaying {
            next: Option<SpeechId>,
            until: Ts,
        },
        /// The head is chosen but authorization is held (AMD's `_authorization_paused`).
        AuthorizationPaused {
            next: SpeechId,
        },
        /// Authorized (`_current_speech`): playing, or inside a tool.
        Current(SpeechId),
    }

    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum Status {
        /// On the queue, or popped as the next speech.
        Queued,
        /// A live preemptive generation: asking the model, not on the queue, waiting for its turn
        /// to commit.
        Preemptive,
        Current,
        /// Step spoken, tools running: neither current nor queued until requeued or finished.
        Working,
        /// A current speech whose tool awaits an inline task: it stays current until its step is
        /// spoken, then becomes `Working`.
        Parked,
        /// Rejected or discarded: the driver interrupted it and it is winding down to its end.
        Discarded,
    }

    #[derive(Debug, Clone)]
    struct Entry {
        /// The speech's handle, from scheduling until release: the queue is where the loop holds
        /// it.
        handle: Arc<SpeechHandle>,
        /// What it was created as. Provenance: an adopted preemptive generation stays a `Guess`
        /// here.
        kind: SpeechKind,
        add_to_chat_ctx: bool,
        status: Status,
        /// An interrupted candidate is never authorized.
        interrupted: bool,
        watchdog: Option<Ts>,
    }

    /// `AgentActivity`'s scheduling state (`_speech_q`, `_current_speech`, `_scheduling_paused`,
    /// `_authorization_paused`, `_preemptive_generation`), and every live speech's handle. Part of
    /// the [`AgentActivity`](crate::agent_activity::AgentActivity).
    #[derive(Debug)]
    pub struct SchedulingTask {
        speeches: BTreeMap<SpeechId, Entry>,
        /// `_speech_q`. Every speech has `SPEECH_PRIORITY_NORMAL` (nothing calls `say(priority=)`),
        /// so the reference's priority queue is a queue.
        speech_q: VecDeque<SpeechId>,
        step: SchedulingStep,
        /// `None` until a speech has played out. Not `Ts::ZERO`, which would delay the first
        /// speech.
        last_playout: Option<Ts>,
        paused: Option<Pause>,
        /// A flag, not a counter: two pauses and one resume resume.
        authorization_paused: bool,
        /// At most one live preemptive generation, with the transcript the model was asked about.
        preemptive_generation: Option<(SpeechId, String)>,
        /// The preflight a preemptive generation is started for, consumed by the `schedule_speech`
        /// that creates it.
        preflight: Option<String>,
        preemptive_generation_count: u32,
        min_consecutive_speech_delay: Duration,
    }

    impl SchedulingTask {
        /// `min_consecutive_speech_delay` is `Duration::ZERO` to disable the gap.
        pub fn new(min_consecutive_speech_delay: Duration) -> Self {
            SchedulingTask {
                speeches: BTreeMap::new(),
                speech_q: VecDeque::new(),
                step: SchedulingStep::Idle,
                last_playout: None,
                paused: None,
                authorization_paused: false,
                preemptive_generation: None,
                preflight: None,
                preemptive_generation_count: 0,
                min_consecutive_speech_delay,
            }
        }

        /// `_current_speech`.
        pub fn current_speech(&self) -> Option<SpeechId> {
            match self.step {
                SchedulingStep::Current(speech) => Some(speech),
                SchedulingStep::Idle
                | SchedulingStep::Delaying { .. }
                | SchedulingStep::AuthorizationPaused { .. } => None,
            }
        }

        fn entry(&self, speech: SpeechId) -> Option<&Entry> {
            self.speeches.get(&speech)
        }

        /// What a speech the queue holds was created as (an adopted preemptive generation stays a
        /// `Guess`).
        pub fn kind(&self, speech: SpeechId) -> Option<SpeechKind> {
            self.entry(speech).map(|e| e.kind)
        }

        /// Where a speech the queue holds is in its life.
        pub fn status(&self, speech: SpeechId) -> Option<Status> {
            self.entry(speech).map(|e| e.status)
        }

        /// The handle of a speech the queue holds (from scheduling until its release).
        pub fn handle(&self, speech: SpeechId) -> Option<&Arc<SpeechHandle>> {
            self.speeches.get(&speech).map(|e| &e.handle)
        }

        pub fn contains(&self, speech: SpeechId) -> bool {
            self.speeches.contains_key(&speech)
        }

        /// No speech is held, live or winding down.
        pub fn is_empty(&self) -> bool {
            self.speeches.is_empty()
        }

        /// Every speech held, oldest first.
        pub fn speech_ids(&self) -> impl DoubleEndedIterator<Item = SpeechId> + '_ {
            self.speeches.keys().copied()
        }

        /// Every speech held with its handle, oldest first.
        pub fn handles(&self) -> impl DoubleEndedIterator<Item = (SpeechId, &Arc<SpeechHandle>)> {
            self.speeches.iter().map(|(id, e)| (*id, &e.handle))
        }

        pub fn preemptive_generation(&self) -> Option<SpeechId> {
            self.preemptive_generation.as_ref().map(|(speech, _)| *speech)
        }

        /// `say(add_to_chat_ctx=..)` for a speech still held; `true` for one already released.
        pub fn add_to_chat_ctx(&self, speech: SpeechId) -> bool {
            self.speeches.get(&speech).is_none_or(|e| e.add_to_chat_ctx)
        }

        pub fn next_deadline(&self) -> Option<Ts> {
            let delay = match self.step {
                SchedulingStep::Delaying { until, .. } => Some(until),
                SchedulingStep::Idle
                | SchedulingStep::AuthorizationPaused { .. }
                | SchedulingStep::Current(_) => None,
            };
            let watchdog = self.speeches.values().filter_map(|e| e.watchdog).min();
            [delay, watchdog].into_iter().flatten().min()
        }

        fn consecutive_speech_delay(&self, now: Ts) -> Option<Duration> {
            if self.min_consecutive_speech_delay.is_zero() {
                return None;
            }
            let elapsed = now.saturating_duration_since(self.last_playout?);
            self.min_consecutive_speech_delay.checked_sub(elapsed).filter(|d| !d.is_zero())
        }

        pub fn is_paused(&self) -> bool {
            self.paused.is_some()
        }

        pub fn authorization_paused(&self) -> bool {
            self.authorization_paused
        }

        /// AMD's `_authorization_paused`: the head is chosen and held unauthorized.
        pub fn set_authorization_paused(&mut self, paused: bool) {
            self.authorization_paused = paused;
        }

        pub fn preemptive_generation_count(&self) -> u32 {
            self.preemptive_generation_count
        }

        /// The current speech has not been interrupted.
        pub fn current_speech_uninterrupted(&self) -> bool {
            self.current_speech().and_then(|c| self.entry(c)).is_some_and(|e| !e.interrupted)
        }

        /// No current speech and none chosen next: at most the gap is owed.
        pub fn no_current_speech(&self) -> bool {
            match self.step {
                SchedulingStep::Idle | SchedulingStep::Delaying { next: None, .. } => true,
                SchedulingStep::Delaying { next: Some(_), .. }
                | SchedulingStep::AuthorizationPaused { .. }
                | SchedulingStep::Current(_) => false,
            }
        }

        /// The next speech, chosen but not yet current (AMD's hold or the consecutive-speech gap).
        pub fn next_speech(&self) -> Option<SpeechId> {
            match self.step {
                SchedulingStep::AuthorizationPaused { next }
                | SchedulingStep::Delaying { next: Some(next), .. } => Some(next),
                SchedulingStep::Idle
                | SchedulingStep::Delaying { next: None, .. }
                | SchedulingStep::Current(_) => None,
            }
        }

        /// `_speech_q` in pop order.
        pub fn speech_q(&self) -> VecDeque<SpeechId> {
            self.speech_q.clone()
        }

        pub fn speech_q_empty(&self) -> bool {
            self.speech_q.is_empty()
        }

        /// The preflight a preemptive generation is started for.
        pub fn set_preflight(&mut self, transcript: String) {
            self.preflight = Some(transcript);
        }

        /// A preemptive generation's preflight, consumed by the `schedule_speech` that creates it.
        pub(super) fn take_preflight(&mut self, preemptive: bool) -> Option<String> {
            if preemptive { self.preflight.take() } else { None }
        }

        /// The speech's entry, holding its handle from here to its release.
        pub(super) fn admit(
            &mut self,
            handle: Arc<SpeechHandle>,
            kind: SpeechKind,
            add_to_chat_ctx: bool,
            status: Status,
        ) {
            let speech = handle.id();
            let entry =
                Entry { handle, kind, add_to_chat_ctx, status, interrupted: false, watchdog: None };
            self.speeches.insert(speech, entry);
        }

        pub(super) fn hold_preemptive_generation(&mut self, speech: SpeechId, preflight: String) {
            self.preemptive_generation = Some((speech, preflight));
            self.preemptive_generation_count += 1;
        }

        pub(super) fn enqueue(&mut self, speech: SpeechId) {
            self.speech_q.push_back(speech);
        }

        /// The interruption watchdogs due by `now`, disarmed.
        pub(super) fn take_due_watchdogs(&mut self, now: Ts) -> Vec<SpeechId> {
            (self.speeches.iter_mut())
                .filter(|(_, e)| e.watchdog.is_some_and(|at| at <= now))
                .map(|(speech, e)| {
                    e.watchdog = None;
                    *speech
                })
                .collect()
        }

        /// `_scheduling_task`'s pass: the owed gap expires where it is read, a parked speech
        /// no longer blocked becomes current again before the queue, and the head is authorized,
        /// armed behind the gap, or held for AMD.
        pub(super) fn scheduling_pass(
            &mut self,
            now: Ts,
            blocked: &BTreeMap<SpeechId, u32>,
        ) -> SchedulingPass {
            let mut released = false;
            let candidate = loop {
                let candidate = match self.step {
                    SchedulingStep::Current(_) => {
                        return SchedulingPass { released, next: NextSpeech::Stay };
                    }
                    SchedulingStep::Delaying { until, .. } if until > now => {
                        return SchedulingPass { released, next: NextSpeech::Stay };
                    }
                    // Expired only here, where it is read; `<=`, since a virtual clock only moves
                    // on demand. A candidate that finished during the gap: the queue is looked at.
                    SchedulingStep::Delaying { next, .. } => {
                        released = true;
                        let Some(next) = next else {
                            self.step = SchedulingStep::Idle;
                            continue;
                        };
                        next
                    }
                    SchedulingStep::AuthorizationPaused { next } => next,
                    // A parked speech whose tool is no longer blocked was mid-tool: it precedes the
                    // queue.
                    SchedulingStep::Idle => {
                        let restorable = self.speeches.iter().find(|(id, e)| {
                            e.status == Status::Parked && !blocked.contains_key(*id)
                        });
                        if let Some((&parked, _)) = restorable {
                            self.step = SchedulingStep::Current(parked);
                            self.set_status(parked, Status::Current);
                            return SchedulingPass { released, next: NextSpeech::Stay };
                        }
                        let Some(speech) = self.speech_q.pop_front() else {
                            return SchedulingPass { released, next: NextSpeech::Stay };
                        };
                        speech
                    }
                };
                let live = self.speeches.get(&candidate);
                if live.is_some_and(|e| !e.interrupted && e.status == Status::Queued) {
                    break candidate;
                }
                // Gone, interrupted or discarded while it waited: forget it and look again.
                self.step = SchedulingStep::Idle;
            };
            if let Some(delay) = self.consecutive_speech_delay(now) {
                let until = now.saturating_add(delay);
                let traced = matches!(self.step, SchedulingStep::Delaying { until: was, .. } if was == until);
                self.step = SchedulingStep::Delaying { next: Some(candidate), until };
                return SchedulingPass { released, next: NextSpeech::Delayed { until, traced } };
            }
            // AMD's hold keeps the head chosen and unauthorized.
            if self.authorization_paused {
                self.step = SchedulingStep::AuthorizationPaused { next: candidate };
                return SchedulingPass { released, next: NextSpeech::Stay };
            }
            self.step = SchedulingStep::Current(candidate);
            self.set_status(candidate, Status::Current);
            SchedulingPass { released, next: NextSpeech::Authorized(candidate) }
        }

        /// The speech was interrupted: never authorized now. The watchdog is armed once (`arm`: not
        /// past the close): its deadline.
        pub(super) fn interrupted(&mut self, speech: SpeechId, now: Ts, arm: bool) -> Option<Ts> {
            let entry = self.speeches.get_mut(&speech)?;
            entry.interrupted = true;
            if entry.watchdog.is_none() && arm {
                let at = now.saturating_add(INTERRUPTION_TIMEOUT);
                entry.watchdog = Some(at);
                return Some(at);
            }
            None
        }

        /// A `Working` speech's next step: back on the queue, its step-scoped interruption cleared;
        /// refused while closing.
        pub(super) fn requeue(&mut self, speech: SpeechId, closing: bool) -> Requeue {
            let Some(entry) =
                self.speeches.get_mut(&speech).filter(|e| e.status == Status::Working)
            else {
                return Requeue::NotWorking;
            };
            if closing {
                entry.status = Status::Discarded;
                return Requeue::Refused;
            }
            // The step boundary ends a step-scoped interruption: its latch and watchdog are
            // cleared.
            entry.interrupted = false;
            entry.status = Status::Queued;
            let watchdog_cleared = entry.watchdog.take().is_some();
            self.speech_q.push_back(speech);
            Requeue::Requeued { watchdog_cleared }
        }

        /// The speech is over: its entry (and handle) go, the current speech and its gap move.
        pub(super) fn finish(&mut self, speech: SpeechId, now: Ts) -> Option<Finished> {
            let entry = self.speeches.remove(&speech)?;
            // A preemptive generation that wound down on its own before the turn committed.
            if self.preemptive_generation.as_ref().is_some_and(|(held, _)| *held == speech) {
                self.preemptive_generation = None;
            }
            self.step = match self.step {
                // The gap measures *end of playout* to start of the next.
                SchedulingStep::Current(current) if current == speech => {
                    self.last_playout = Some(now);
                    SchedulingStep::Idle
                }
                // The gap owed to a finished speech stands for whoever is behind.
                SchedulingStep::Delaying { next: Some(next), until } if next == speech => {
                    SchedulingStep::Delaying { next: None, until }
                }
                SchedulingStep::AuthorizationPaused { next } if next == speech => {
                    SchedulingStep::Idle
                }
                step => step,
            };
            let working = self.speeches.values().any(|e| e.status == Status::Working);
            let quiet = !working
                && matches!(
                    self.step,
                    SchedulingStep::Idle | SchedulingStep::Delaying { next: None, .. }
                );
            Some(Finished { watchdog: entry.watchdog.is_some(), quiet })
        }

        /// `_pause_scheduling_task`: one more promise; the close's drain outranks the pause it
        /// joins.
        pub(super) fn pause(&mut self, cause: PauseCause, done: tokio::sync::oneshot::Sender<()>) {
            match &mut self.paused {
                Some(pause) => {
                    pause.acks.push(done);
                    if cause == PauseCause::Close {
                        pause.cause = PauseCause::Close;
                    }
                }
                None => self.paused = Some(Pause { cause, acks: vec![done] }),
            }
        }

        /// The pause a frame change or a host drain caused, lifted: its callers.
        pub(super) fn resume_frame_pause(
            &mut self,
        ) -> Option<Vec<tokio::sync::oneshot::Sender<()>>> {
            let caused = |p: &mut Pause| matches!(p.cause, PauseCause::Handoff | PauseCause::Drain);
            self.paused.take_if(caused).map(|p| p.acks)
        }

        pub(super) fn take_pause(&mut self) -> Option<Vec<tokio::sync::oneshot::Sender<()>>> {
            self.paused.take().map(|p| p.acks)
        }

        /// The close: every watchdog disarmed (the speeches whose went), and an owed or held
        /// next speech freed (`true` when an owed gap was released).
        pub(super) fn close(&mut self) -> (Vec<SpeechId>, bool) {
            let mut cleared = Vec::new();
            for (speech, entry) in &mut self.speeches {
                if entry.watchdog.take().is_some() {
                    cleared.push(*speech);
                }
            }
            let released = match self.step {
                SchedulingStep::Delaying { .. } => {
                    self.step = SchedulingStep::Idle;
                    true
                }
                SchedulingStep::AuthorizationPaused { .. } => {
                    self.step = SchedulingStep::Idle;
                    false
                }
                SchedulingStep::Idle | SchedulingStep::Current(_) => false,
            };
            (cleared, released)
        }

        /// A blocked current speech is parked: it stays current while its step plays.
        pub(super) fn park_if_blocked(&mut self, blocked: &BTreeMap<SpeechId, u32>) {
            if let SchedulingStep::Current(current) = self.step
                && blocked.contains_key(&current)
                && self.entry(current).is_some_and(|e| e.status == Status::Current)
            {
                self.set_status(current, Status::Parked);
            }
        }

        /// Unblocked, a parked speech is current again, or becomes current when none is.
        pub(super) fn unpark(&mut self, speech: SpeechId) {
            if !self.entry(speech).is_some_and(|e| e.status == Status::Parked) {
                return;
            }
            match self.step {
                SchedulingStep::Current(current) if current == speech => {
                    self.set_status(speech, Status::Current)
                }
                SchedulingStep::Idle => {
                    self.step = SchedulingStep::Current(speech);
                    self.set_status(speech, Status::Current);
                }
                SchedulingStep::Current(_)
                | SchedulingStep::Delaying { .. }
                | SchedulingStep::AuthorizationPaused { .. } => {}
            }
        }

        /// The pause's callers, once nothing it waits on is outstanding (a blocked speech excepted
        /// once `Working`).
        pub(super) fn settle_pause(
            &mut self,
            blocked: &BTreeMap<SpeechId, u32>,
        ) -> Vec<tokio::sync::oneshot::Sender<()>> {
            let Some(pause) = &mut self.paused else { return Vec::new() };
            let outstanding = (self.speeches.iter())
                .any(|(id, e)| !(blocked.contains_key(id) && e.status == Status::Working));
            if outstanding {
                return Vec::new();
            }
            std::mem::take(&mut pause.acks)
        }

        /// `_cancel_preemptive_generation`: the preflight goes; the live preemptive generation, if
        /// it still has an entry, is discarded and returned for its interruption.
        pub(super) fn cancel_preemptive_generation(&mut self) -> Option<SpeechId> {
            self.preflight = None;
            let (speech, _) = self.preemptive_generation.take()?;
            self.entry(speech)?;
            self.set_status(speech, Status::Discarded);
            Some(speech)
        }

        /// The turn committed `committed`: the preemptive generation asked about those words is
        /// queued as its reply, any other discarded. The per-turn retry count starts over.
        pub(super) fn adopt_preemptive_generation(
            &mut self,
            committed: &str,
        ) -> Option<(SpeechId, PreemptiveVerdict)> {
            (self.preemptive_generation_count, self.preflight) = (0, None);
            let (speech, preflight) = self.preemptive_generation.take()?;
            let interrupted = self.entry(speech)?.interrupted;
            let verdict = reconcile_preemptive_generation(&preflight, committed, interrupted);
            match verdict {
                PreemptiveVerdict::Reuse => {
                    self.set_status(speech, Status::Queued);
                    self.speech_q.push_back(speech);
                }
                PreemptiveVerdict::Discard(_) => self.set_status(speech, Status::Discarded),
            }
            Some((speech, verdict))
        }

        /// The step was spoken: the current speech is released and becomes `Working`, as does a
        /// parked speech (requeueing is the way back). No `listening`: tools may still run.
        pub(in crate::agent_activity) fn spoken(&mut self, speech: SpeechId, now: Ts) {
            if self.step == SchedulingStep::Current(speech) {
                self.step = SchedulingStep::Idle;
            } else if self.entry(speech).is_none_or(|e| e.status != Status::Parked) {
                return;
            }
            self.last_playout = Some(now);
            self.set_status(speech, Status::Working);
        }

        fn set_status(&mut self, speech: SpeechId, status: Status) {
            if let Some(entry) = self.speeches.get_mut(&speech) {
                entry.status = status;
            }
        }

        /// Debug builds only, at the end of each pass: the state is consistent between wakes.
        pub fn check_invariants(&self, closing: bool) {
            let status = |id: &SpeechId| self.speeches.get(id).map(|e| e.status);
            let preemptive = self.speeches.iter().filter(|(_, e)| e.status == Status::Preemptive);
            debug_assert!(
                preemptive.map(|(id, _)| *id).eq(self.preemptive_generation()),
                "the preemptive generation slot and the Preemptive entries disagree"
            );
            match self.step {
                // The current speech is `Current`, or parked: blocked for an inline task, its step
                // still playing.
                SchedulingStep::Current(speech) => debug_assert!(
                    matches!(status(&speech), Some(Status::Current | Status::Parked)),
                    "the current speech is neither current nor parked: {:?}",
                    status(&speech)
                ),
                SchedulingStep::Delaying { next: Some(next), .. }
                | SchedulingStep::AuthorizationPaused { next } => debug_assert_eq!(
                    status(&next),
                    Some(Status::Queued),
                    "the next speech {next:?} was released or is not queued"
                ),
                SchedulingStep::Delaying { next: None, .. } | SchedulingStep::Idle => {}
            }
            let current = self.speeches.values().filter(|e| e.status == Status::Current).count();
            debug_assert!(current <= 1, "two speeches are current");
            // The queue holds queued speeches (and stale ids of released ones).
            for id in &self.speech_q {
                let s = status(id);
                debug_assert!(s.is_none_or(|s| s == Status::Queued), "{id:?} is queued as {s:?}");
            }
            if closing {
                debug_assert!(
                    self.preemptive_generation.is_none(),
                    "a preemptive generation outlived Closing"
                );
                debug_assert!(self.paused.is_none(), "a pause outlived Closing");
                let watchdog = self.speeches.values().any(|e| e.watchdog.is_some());
                debug_assert!(!watchdog, "a watchdog outlived Closing");
            }
            if self.paused.is_some() {
                debug_assert!(
                    self.preemptive_generation.is_none(),
                    "a preemptive generation outlived a pause"
                );
            }
        }
    }

    /// What a scheduling pass did: an owed gap expired (`FloorReleased`), then what the next
    /// speech is.
    pub(super) struct SchedulingPass {
        pub(super) released: bool,
        pub(super) next: NextSpeech,
    }

    pub(super) enum NextSpeech {
        /// A current speech, a gap owed, nothing queued, or held for AMD: nothing to authorize.
        Stay,
        /// The gap is owed until `until`; `traced` when that deadline was already armed.
        Delayed {
            until: Ts,
            traced: bool,
        },
        Authorized(SpeechId),
    }

    pub(super) enum Requeue {
        NotWorking,
        /// Closing: discarded, to be refused.
        Refused,
        Requeued {
            watchdog_cleared: bool,
        },
    }

    pub(super) struct Finished {
        /// Its watchdog was armed.
        pub(super) watchdog: bool,
        /// No current speech and nothing in its tools: `listening`.
        pub(super) quiet: bool,
    }
}

/// Not `SpeechHandle::id`, the Python-visible string the pure tier cannot mint.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct SpeechId(pub u64);

/// Priority and `user_initiated` derive from it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, lk_agents_abi::Vocabulary)]
pub enum SpeechKind {
    TurnReply,
    Say,
    GenerateReply,
    /// A speculative reply on a preflight transcript, **not queued** until the turn adopts it.
    Guess,
    Realtime,
}

impl SpeechKind {
    /// `SpeechCreatedEvent.source`: only `say()` is `say`; everything else is `generate_reply`.
    pub const fn as_source_str(self) -> &'static str {
        match self {
            SpeechKind::Say => "say",
            SpeechKind::TurnReply
            | SpeechKind::GenerateReply
            | SpeechKind::Guess
            | SpeechKind::Realtime => "generate_reply",
        }
    }

    /// `speech_created(user_initiated=..)`: the host asked for this one by name.
    pub const fn user_initiated(self) -> bool {
        match self {
            SpeechKind::Say | SpeechKind::GenerateReply => true,
            SpeechKind::TurnReply | SpeechKind::Guess | SpeechKind::Realtime => false,
        }
    }

    /// What an open run owns at creation.
    pub const fn session_level(self) -> bool {
        match self {
            SpeechKind::Say | SpeechKind::GenerateReply => true,
            SpeechKind::TurnReply | SpeechKind::Guess | SpeechKind::Realtime => false,
        }
    }

    /// A preemptive generation must not be authorised before the turn commits.
    pub const fn scheduled(self) -> bool {
        match self {
            SpeechKind::Guess => false,
            SpeechKind::TurnReply
            | SpeechKind::Say
            | SpeechKind::GenerateReply
            | SpeechKind::Realtime => true,
        }
    }
}

/// Either way the speech is force-interrupted.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error, lk_agents_abi::Vocabulary)]
pub enum Rejected {
    /// Scheduling is paused (draining). The driver raises the reference's `RuntimeError` verbatim.
    #[error(
        "cannot schedule new speech, the speech scheduling is draining/pausing, the speech will be cancelled"
    )]
    Draining,
    /// The session is closing. The reference logs a warning and returns normally.
    #[error(
        "attempting to schedule a new SpeechHandle, but the scheduling_task is not running, the speech will be cancelled"
    )]
    Stopped,
}

/// A handoff lifts only its own.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PauseCause {
    Handoff,
    /// The host's `drain()`: nothing new is scheduled, lifted by the frame that replaces it.
    Drain,
    /// Closing: speeches in flight finish (tools included); the hard edge follows the settle.
    Close,
}

/// Why no preemptive generation is started, so a trace names the guard.
#[derive(Debug, Clone, Copy, PartialEq, Eq, lk_agents_abi::Vocabulary)]
pub enum PreemptRefusal {
    Disabled,
    Realtime,
    SchedulingPaused,
    AgentSpeaking,
    RetriesExhausted,
    TooLong,
    ManualTurn,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, lk_agents_abi::Vocabulary)]
pub enum PreemptiveDiscard {
    /// The committed words are not the words the model was asked about.
    WordDelta,
    Interrupted,
    /// A newer preflight asked again; the older preemptive generation is not raced, it is replaced.
    Superseded,
    /// The turn the preemptive generation was for went away without a reply, or the preemptive
    /// generation's request failed.
    TurnAbandoned,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PreemptiveVerdict {
    /// The model was asked the question the turn ended up committing: queue the parked reply.
    Reuse,
    Discard(PreemptiveDiscard),
}

/// Word-level equivalence: case folded, punctuation ignored, whitespace normalised.
pub fn same_words(a: &str, b: &str) -> bool {
    words(a).eq(words(b))
}

fn words(s: &str) -> impl Iterator<Item = String> + '_ {
    s.split_whitespace()
        .map(|w| {
            w.chars()
                .filter(|c| c.is_alphanumeric())
                .flat_map(char::to_lowercase)
                .collect::<String>()
        })
        .filter(|w| !w.is_empty())
}

/// Interrupted wins over the words.
pub fn reconcile_preemptive_generation(
    preflight: &str,
    committed: &str,
    interrupted: bool,
) -> PreemptiveVerdict {
    if interrupted {
        return PreemptiveVerdict::Discard(PreemptiveDiscard::Interrupted);
    }
    if !same_words(preflight, committed) {
        return PreemptiveVerdict::Discard(PreemptiveDiscard::WordDelta);
    }
    PreemptiveVerdict::Reuse
}

impl Driver {
    /// `_schedule_speech`. Every speech is born here: announced (`SpeechCreated`), recorded
    /// (`ReplyCreated`), then queued, held as the preemptive generation, or refused -- journalled,
    /// interrupted (forced) and `false`.
    pub(crate) fn schedule_speech(
        &mut self,
        now: Ts,
        handle: &Arc<SpeechHandle>,
        kind: SpeechKind,
        add_to_chat_ctx: bool,
        host_asked: bool,
        cycle: &mut Cycle,
    ) -> bool {
        let speech = handle.id();
        {
            let user_initiated = kind.user_initiated() || host_asked;
            let speech = Arc::clone(handle);
            cycle.machine().emit(SessionEvent::SpeechCreated { speech, kind, user_initiated });
        }
        cycle.trace(SpeechStep::ReplyCreated { speech });
        // A preemptive generation's preflight is taken before the previous preemptive generation is
        // discarded, which clears it.
        let preflight =
            self.activity.scheduling_task_mut().take_preflight(kind == SpeechKind::Guess);
        // Closing first, so a forced request into a closing session is still `Stopped`. `Closing`
        // and a pause discard the preemptive generation, so a preemptive generation behind them is
        // refused too.
        let rejected =
            match (self.session.closing_past_edge(), self.activity.scheduling_task().is_paused()) {
                (true, _) => Some(Rejected::Stopped),
                (false, true) => Some(Rejected::Draining),
                (false, false) => None,
            };
        let status = match (rejected, kind) {
            (Some(_), _) => Status::Discarded,
            (None, SpeechKind::Guess) => Status::Preemptive,
            (None, _) => Status::Queued,
        };
        if status == Status::Preemptive {
            // Asking again supersedes the previous preemptive generation rather than racing it.
            self.cancel_preemptive_generation(now, PreemptiveDiscard::Superseded, cycle);
        }
        let s = self.activity.scheduling_task_mut();
        s.admit(Arc::clone(handle), kind, add_to_chat_ctx, status);
        match rejected {
            Some(reason) => self.reject_speech(now, speech, reason, cycle),
            None if status == Status::Preemptive => {
                s.hold_preemptive_generation(speech, preflight.unwrap_or_default())
            }
            None => s.enqueue(speech),
        }
        rejected.is_none()
    }

    /// A refused speech is still interrupted (forced), or its eager task parks in
    /// `wait_for_authorization` forever: `Closing` past the close, else `ScheduleRejected`.
    fn reject_speech(&mut self, now: Ts, speech: SpeechId, reason: Rejected, cycle: &mut Cycle) {
        cycle.trace(SpeechStep::ScheduleRejected { speech, reason });
        let cause = match reason {
            Rejected::Stopped => InterruptCause::Closing,
            Rejected::Draining => InterruptCause::ScheduleRejected,
        };
        let _ = self.interrupt_speech(now, speech, cause, true, cycle);
        // The server keeps generating a cancelled realtime turn until told.
        if self.activity.rt_session().is_some() {
            self.realtime_interrupt(cycle);
        }
        // Born past the close's edge: released here, since the loop may stop first.
        if reason == Rejected::Stopped {
            cycle.trace(CloseStep::Performed(CloseAct::Released { speech }));
            self.release_speech(now, speech, cycle);
        }
    }

    /// One `_scheduling_task` pass per cycle, so `Authorized` lands next to the steps that led to
    /// it; then the turn machine's `PreemptiveGeneration` asks.
    pub(crate) fn pump_schedule(&mut self, now: Ts, cycle: &mut Cycle) {
        self.scheduling_task(now, cycle);
        self.activity.scheduling_task().check_invariants(self.session.closing_past_edge());
        let preflights: Vec<(String, Option<Ts>)> = cycle
            .peek()
            .iter()
            .filter_map(|e| match e {
                crate::agent_session::cycle::Effect::Emit(SessionEvent::PreemptiveGeneration(pg)) => {
                    Some((pg.new_transcript.clone(), pg.started_speaking_at))
                }
                _ => None,
            })
            .collect();
        for (transcript, started_speaking_at) in preflights {
            self.on_preemptive_generation(now, transcript, started_speaking_at, cycle);
        }
    }

    /// `_scheduling_task`: due interruption watchdogs, then the current speech. The
    /// `min_consecutive_speech_delay` gap is a deadline on the main `select!`, not a sleep.
    fn scheduling_task(&mut self, now: Ts, cycle: &mut Cycle) {
        let due = self.activity.scheduling_task_mut().take_due_watchdogs(now);
        for speech in due {
            cycle.trace(SpeechStep::WatchdogCleared { speech });
            // `SpeechHandle._cancel`: cancel, mark done and release, since the aborted task will
            // never report `Done`.
            if self
                .activity
                .scheduling_task()
                .handle(speech)
                .is_some_and(|h| h.on_interruption_timeout())
            {
                cycle.trace(InterruptStep::InterruptionTimedOut { speech });
                if !self.session.is_closing() {
                    self.end_live_tools(now, speech, cycle);
                }
                self.release_speech(now, speech, cycle);
            }
        }
        if self.session.closing_past_edge() {
            return;
        }
        let blocked = self.activity.tasks().blocked().clone();
        let SchedulingPass { released, next } =
            self.activity.scheduling_task_mut().scheduling_pass(now, &blocked);
        if released {
            cycle.trace(SpeechStep::FloorReleased);
        }
        let candidate = match next {
            NextSpeech::Stay => return,
            NextSpeech::Delayed { until, traced: false } => {
                return cycle.trace(SpeechStep::FloorArmed { until });
            }
            NextSpeech::Delayed { traced: true, .. } => return,
            NextSpeech::Authorized(candidate) => candidate,
        };
        let Some(handle) = self.activity.scheduling_task().handle(candidate).cloned() else {
            return;
        };
        handle.authorize_generation();
        self.release_paused_speech(candidate, cycle);
        cycle.trace(SpeechStep::Authorized { speech: candidate });
        self.shared.launch.note_authorized(candidate);
    }

    /// An interrupted candidate is never authorized; the watchdog is armed on the session clock.
    pub(crate) fn on_speech_interrupted(&mut self, now: Ts, speech: SpeechId, cycle: &mut Cycle) {
        // Nothing fires after the close: every handle is interrupted there and the loop exits.
        let closing = self.session.closing_past_edge();
        if let Some(at) = self.activity.scheduling_task_mut().interrupted(speech, now, !closing) {
            cycle.trace(SpeechStep::WatchdogArmed { speech, at });
        }
    }

    /// The reply's tools are done and it has a next step: a `Working` speech goes back on the
    /// queue behind whatever was queued since (any other is left alone); closing refuses it.
    pub(super) fn requeue_speech(&mut self, now: Ts, speech: SpeechId, cycle: &mut Cycle) {
        let closing = self.session.closing_past_edge();
        match self.activity.scheduling_task_mut().requeue(speech, closing) {
            Requeue::NotWorking => {}
            Requeue::Refused => self.reject_speech(now, speech, Rejected::Stopped, cycle),
            Requeue::Requeued { watchdog_cleared } => {
                if watchdog_cleared {
                    cycle.trace(SpeechStep::WatchdogCleared { speech });
                }
            }
        }
    }

    /// The speech is over (`Done`, `Failed` or the watchdog): the current speech and its gap, then
    /// `_on_pipeline_reply_done`'s `listening` when nothing speaks and nothing is in its tools.
    pub(super) fn speech_finished(&mut self, now: Ts, speech: SpeechId, cycle: &mut Cycle) {
        let Some(Finished { watchdog, quiet }) =
            self.activity.scheduling_task_mut().finish(speech, now)
        else {
            return;
        };
        if watchdog {
            cycle.trace(SpeechStep::WatchdogCleared { speech });
        }
        // A self-replying realtime model is still composing the reply its tools asked for: the
        // agent stays `thinking` (`agent_activity.py:4406-4410`).
        if quiet && !self.activity.realtime_turns().auto_reply_expected() {
            self.set_agent_state(now, AgentState::Listening, cycle);
        }
        self.settle_scheduling_pause(cycle);
    }

    /// `_pause_scheduling_task`: new speech is refused (tool replies excepted) and queued speech
    /// still plays; `done` is answered once nothing outstanding remains. Two pauses before the
    /// drain completes are two promises; a closing session refuses (drops) it.
    pub(crate) fn pause_scheduling_task(
        &mut self,
        now: Ts,
        cause: PauseCause,
        done: tokio::sync::oneshot::Sender<()>,
        cycle: &mut Cycle,
    ) {
        if self.session.closing_past_edge() {
            return refuse_pause(vec![done], CLOSING, cycle);
        }
        self.activity.scheduling_task_mut().pause(cause, done);
        let blocked = self.activity.tasks().blocked().clone();
        self.activity.scheduling_task_mut().park_if_blocked(&blocked);
        self.cancel_preemptive_generation(now, PreemptiveDiscard::TurnAbandoned, cycle);
        self.settle_scheduling_pause(cycle);
    }

    /// `_resume_scheduling_task` at the frame swap: a preemptive generation for the old frame is
    /// discarded, and only the pause the frame change (or the host's drain) caused is lifted.
    pub(crate) fn resume_scheduling_task(&mut self, now: Ts, cycle: &mut Cycle) {
        self.cancel_preemptive_generation(now, PreemptiveDiscard::TurnAbandoned, cycle);
        if let Some(acks) = self.activity.scheduling_task_mut().resume_frame_pause() {
            refuse_pause(acks, HANDOFF, cycle);
        }
    }

    /// The close: watchdogs go with their speeches, the current speech is released, a pending
    /// preemptive generation discarded, a drain-waiting pause refused, and nothing is authorized
    /// again.
    pub(crate) fn close_scheduling(&mut self, now: Ts, cycle: &mut Cycle) {
        let (cleared, delay_released) = self.activity.scheduling_task_mut().close();
        for speech in cleared {
            cycle.trace(SpeechStep::WatchdogCleared { speech });
        }
        if delay_released {
            cycle.trace(SpeechStep::FloorReleased);
        }
        self.cancel_preemptive_generation(now, PreemptiveDiscard::TurnAbandoned, cycle);
        if let Some(acks) = self.activity.scheduling_task_mut().take_pause() {
            refuse_pause(acks, CLOSING, cycle);
        }
    }

    /// `_add_drain_blocked_tasks` and its release, at the first block and the last unblock. A
    /// blocked current speech is parked: it stays current while its step plays (freeing it let the
    /// task's speech interleave with the parent's). Unblocked, it is current again, or becomes
    /// current when none is.
    pub(crate) fn set_drain_blocked(&mut self, speech: SpeechId, blocked: bool, cycle: &mut Cycle) {
        if blocked {
            let blocked = self.activity.tasks().blocked().clone();
            self.activity.scheduling_task_mut().park_if_blocked(&blocked);
        } else {
            self.activity.scheduling_task_mut().unpark(speech);
        }
        self.settle_scheduling_pause(cycle);
    }

    /// Answer every pending pause once nothing it waits on is outstanding (released, tools
    /// included). A blocked speech is excepted once `Working`: the pause came from inside its tool.
    pub(super) fn settle_scheduling_pause(&mut self, cycle: &mut Cycle) {
        let blocked = self.activity.tasks().blocked().clone();
        for done in self.activity.scheduling_task_mut().settle_pause(&blocked) {
            // A dropped receiver is a caller that stopped waiting -- ordinary.
            let _ = done.send(());
            cycle.trace(SpeechStep::SchedulingPauseSettled);
        }
    }

    /// `_cancel_preemptive_generation`: a live preemptive generation is discarded.
    pub(crate) fn cancel_preemptive_generation(
        &mut self,
        now: Ts,
        reason: PreemptiveDiscard,
        cycle: &mut Cycle,
    ) {
        if let Some(speech) = self.activity.scheduling_task_mut().cancel_preemptive_generation() {
            self.discard_preemptive_generation(now, speech, reason, cycle);
        }
    }

    /// The turn committed: a preemptive generation asked about the committed words is its reply and
    /// is queued; any other is discarded. The per-turn retry count starts over.
    pub(super) fn adopt_preemptive_generation(
        &mut self,
        now: Ts,
        committed: &str,
        cycle: &mut Cycle,
    ) -> Option<SpeechId> {
        let (speech, verdict) =
            self.activity.scheduling_task_mut().adopt_preemptive_generation(committed)?;
        match verdict {
            // Adopted by construction: a pause and `Closing` discard the preemptive generation
            // first.
            PreemptiveVerdict::Reuse => {
                if let Some(handle) = self.activity.scheduling_task().handle(speech) {
                    handle.mark_scheduled();
                }
                cycle.trace(TurnStep::GuessReconciled { speech, verdict });
                Some(speech)
            }
            PreemptiveVerdict::Discard(reason) => {
                self.discard_preemptive_generation(now, speech, reason, cycle);
                None
            }
        }
    }

    /// A superseded preemptive generation must be interrupted, or it parks forever holding its LLM
    /// stream.
    fn discard_preemptive_generation(
        &mut self,
        now: Ts,
        speech: SpeechId,
        reason: PreemptiveDiscard,
        cycle: &mut Cycle,
    ) {
        let verdict = PreemptiveVerdict::Discard(reason);
        cycle.trace(TurnStep::GuessReconciled { speech, verdict });
        let _ = self.interrupt_speech(now, speech, InterruptCause::Superseded, true, cycle);
    }

    /// `_pause_scheduling_task()`: journalled with the speeches it waits for, then asked of the
    /// scheduling task; `done` fires once they are all over.
    pub(crate) fn pause_scheduling(
        &mut self,
        now: Ts,
        cause: PauseCause,
        done: tokio::sync::oneshot::Sender<()>,
        cycle: &mut Cycle,
    ) {
        let except = self.activity.tasks().blocked().keys().copied().collect();
        cycle.trace(SpeechStep::SchedulingPaused { except });
        self.pause_scheduling_task(now, cause, done, cycle);
    }

    /// `_current_speech`'s handle.
    pub(crate) fn current_handle(&self) -> Option<Arc<SpeechHandle>> {
        let scheduling = self.activity.scheduling_task();
        scheduling.current_speech().and_then(|id| scheduling.handle(id).cloned())
    }

    /// The facts about `_current_speech` the turn machine's guards read.
    pub(crate) fn speech_guard(&self) -> Option<crate::agent_activity::pause::CurrentSpeech> {
        self.current_handle().map(|h| crate::agent_activity::pause::CurrentSpeech {
            id: h.id(),
            interrupted: h.interrupted(),
            allow_interruptions: h.allow_interruptions(),
        })
    }

    pub(crate) fn is_realtime_speech(&self, speech: SpeechId) -> bool {
        self.activity.scheduling_task().kind(speech) == Some(SpeechKind::Realtime)
    }
}

/// A pause that can no longer complete truthfully: its callers are released (the channel drops)
/// and the journal has the reason.
fn refuse_pause(
    acks: Vec<tokio::sync::oneshot::Sender<()>>,
    cause: &'static str,
    cycle: &mut Cycle,
) {
    for done in acks {
        drop(done);
        cycle.trace(SpeechStep::SchedulingPauseRefused { cause });
    }
}
