//! Registers every `src/rules/*.rs` (except `mod.rs`) in `RULES`, in file-name order; the rule
//! type is the file name in CamelCase, so adding a rule is adding a file.

#![allow(
    clippy::unwrap_used,
    clippy::print_stdout,
    reason = "a build script fails the build on a bad source tree and talks to Cargo through stdout"
)]

use std::{env, fs, path::Path};

mod build_calibration;
mod build_registration;

fn capitalised(word: &str) -> String {
    let mut chars = word.chars();
    chars.next().map(|c| c.to_uppercase().collect::<String>() + chars.as_str()).unwrap_or_default()
}

fn main() {
    let root = env::var("CARGO_MANIFEST_DIR").unwrap();
    let root = Path::new(&root);
    build_calibration::generate(root);
    build_registration::check_test_modules(root);
    let rules = root.join("src/rules");
    println!("cargo:rerun-if-changed={}", rules.display());

    let mut names: Vec<String> = fs::read_dir(&rules)
        .expect("src/rules exists")
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|e| e == "rs"))
        .filter_map(|path| path.file_stem().map(|s| s.to_string_lossy().into_owned()))
        .filter(|name| name != "mod")
        .collect();
    names.sort();
    // The text driver's rules (`impl TextRule`) judge its own recording: a registry of their own.
    let (text, names): (Vec<String>, Vec<String>) = names.into_iter().partition(|name| {
        let source = fs::read_to_string(rules.join(format!("{name}.rs"))).unwrap();
        source.contains("impl TextRule for")
    });
    write_registry(&rules, &text, "TEXT_RULES", "TextRegistered", "TextRule", "text_rules.rs");
    write_registry(&rules, &names, "RULES", "Registered", "Rule", "rules.rs");
}

fn write_registry(
    rules: &Path,
    names: &[String],
    list: &str,
    registered: &str,
    rule_trait: &str,
    out_file: &str,
) {
    let mut out = String::from("// Generated by build.rs from src/rules/*.rs. Do not edit.\n");
    for name in names {
        let file = rules.join(format!("{name}.rs"));
        out.push_str(&format!("#[path = {:?}]\nmod {name};\n", file.display().to_string()));
    }
    out.push_str(&format!(
        "\n/// Every rule, one per file, in file-name order.\npub const {list}: &[{registered}] = &[\n"
    ));
    for name in names {
        let rule: String = name.split('_').map(capitalised).collect();
        out.push_str(&format!(
            "    {registered} {{ contract: <{name}::{rule} as {rule_trait}>::CONTRACT, on_complete: <{name}::{rule} as {rule_trait}>::on_complete }},\n"
        ));
    }
    out.push_str("];\n");

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join(out_file);
    fs::write(dest, out).unwrap();
}
