//! Discovers the rules: every `src/rules/*.rs` except `mod.rs` becomes a module and an entry in
//! `RULES`, in file-name order; the rule type is the file name in CamelCase. Cargo reruns this whenever the directory changes, so adding a
//! rule is adding a file. The generated code is `include!`d by `src/rules/mod.rs`.
use std::{env, fs, path::Path};

fn capitalised(word: &str) -> String {
    let mut chars = word.chars();
    chars.next().map(|c| c.to_uppercase().collect::<String>() + chars.as_str()).unwrap_or_default()
}

fn main() {
    let rules = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("src/rules");
    println!("cargo:rerun-if-changed={}", rules.display());

    let mut names: Vec<String> = fs::read_dir(&rules)
        .expect("src/rules exists")
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|e| e == "rs"))
        .filter_map(|path| path.file_stem().map(|s| s.to_string_lossy().into_owned()))
        .filter(|name| name != "mod")
        .collect();
    names.sort();

    let mut out = String::from("// Generated by build.rs from src/rules/*.rs. Do not edit.\n");
    for name in &names {
        let file = rules.join(format!("{name}.rs"));
        out.push_str(&format!("#[path = {:?}]\nmod {name};\n", file.display().to_string()));
    }
    out.push_str("\n/// Every rule, one per file, in file-name order.\npub const RULES: &[Registered] = &[\n");
    for name in &names {
        let rule: String = name.split('_').map(capitalised).collect();
        out.push_str(&format!(
            "    Registered {{ contract: <{name}::{rule} as Rule>::CONTRACT, on_complete: <{name}::{rule} as Rule>::on_complete }},\n"
        ));
    }
    out.push_str("];\n\n/// The rule files, in the same order, for the id check.\n#[cfg(test)]\nconst FILES: &[&str] = &[\n");
    for name in &names {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n");

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("rules.rs");
    fs::write(dest, out).unwrap();
}
