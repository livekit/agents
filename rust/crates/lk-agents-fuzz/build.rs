//! Registers every rule under `src/rules/<domain>/` in file-name order; the rule type is the file
//! name in CamelCase, so adding a rule is adding a file. The rules in `src/rules/text/` judge the
//! text driver's recording and form their own registry.

#![allow(
    clippy::unwrap_used,
    clippy::print_stdout,
    reason = "a build script fails the build on a bad source tree and talks to Cargo through stdout"
)]

use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn capitalised(word: &str) -> String {
    let mut chars = word.chars();
    chars.next().map(|c| c.to_uppercase().collect::<String>() + chars.as_str()).unwrap_or_default()
}

fn main() {
    let root = env::var("CARGO_MANIFEST_DIR").unwrap();
    let rules = Path::new(&root).join("src/rules");
    let (mut text, mut voice) = (Vec::new(), Vec::new());
    println!("cargo:rerun-if-changed={}", rules.display());
    for domain in fs::read_dir(&rules).unwrap().flatten() {
        let dir = domain.path();
        if !dir.is_dir() {
            assert!(
                domain.file_name() == "mod.rs",
                "{}: a rule lives in a domain directory",
                dir.display()
            );
            continue;
        }
        println!("cargo:rerun-if-changed={}", dir.display());
        let files = fs::read_dir(&dir).unwrap().flatten().map(|entry| entry.path());
        let files = files.filter(|path| path.extension().is_some_and(|e| e == "rs"));
        if domain.file_name() == "text" { text.extend(files) } else { voice.extend(files) }
    }
    write_registry(text, "TEXT_RULES", "TextRegistered", "TextRule", "text_rules.rs");
    write_registry(voice, "RULES", "Registered", "Rule", "rules.rs");
}

fn write_registry(
    mut files: Vec<PathBuf>,
    list: &str,
    registered: &str,
    rule_trait: &str,
    out_file: &str,
) {
    let name = |path: &PathBuf| path.file_stem().unwrap().to_string_lossy().into_owned();
    files.sort_by_key(name);
    let mut out = String::from("// Generated by build.rs from src/rules/. Do not edit.\n");
    for file in &files {
        out.push_str(&format!("#[path = {:?}]\nmod {};\n", file.display().to_string(), name(file)));
    }
    out.push_str(&format!(
        "\n/// Every rule, one per file, in file-name order.\npub const {list}: &[{registered}] = &[\n"
    ));
    for file in &files {
        let name = name(file);
        let rule: String = name.split('_').map(capitalised).collect();
        out.push_str(&format!(
            "    {registered} {{ contract: <{name}::{rule} as {rule_trait}>::CONTRACT, on_complete: <{name}::{rule} as {rule_trait}>::on_complete }},\n"
        ));
    }
    out.push_str("];\n");
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join(out_file), out).unwrap();
}
