//! How a contract reports: one expectation at a time, against a subject with a stable identity.
//!
//! The identity matters more than the message. Shrinking a finding means running shorter and
//! shorter cases and asking "is this still the same problem", and the only honest answer comes
//! from the contract plus the thing it is about -- never from the wording, which changes as the
//! case changes.
use std::collections::BTreeMap;

use crate::{
    drive::Case,
    record::{Kind, Recording},
    rules,
};

/// What a failed expectation is about.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, serde::Serialize, serde::Deserialize)]
pub enum Subject {
    /// The run as a whole.
    Session,
    /// One speech, by the id the driver minted for it.
    Speech(u64),
    /// The n-th resource of a kind, named the way a case names one.
    Resource(Kind, u32),
}

#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct Failure {
    pub contract: String,
    pub subject: Subject,
    /// Diagnostic text. Read by a person, never compared.
    pub detail: String,
}

/// Accumulates one contract's expectations over one recording.
pub struct Check {
    contract: &'static str,
    /// How many expectations this contract actually made. Zero means it never applied to this
    /// run, which a report must distinguish from passing.
    pub expectations: u32,
    pub failures: Vec<Failure>,
}

impl Check {
    pub fn new(contract: &'static str) -> Self {
        Check { contract, expectations: 0, failures: Vec::new() }
    }

    /// Record one expectation about a subject. Reaching this call is what marks the rule as
    /// applying to the run: a rule that returns before its first `expect` did not apply, and the
    /// report says so rather than counting it as a pass.
    pub fn expect(&mut self, subject: impl Into<Subject>, holds: bool, detail: impl Into<String>) {
        self.expectations += 1;
        if !holds {
            self.failures.push(Failure {
                contract: self.contract.to_string(),
                subject: subject.into(),
                detail: detail.into(),
            });
        }
    }

    /// [`Check::expect`] for a loop over every frame of a run: the detail is only written when the
    /// expectation fails, because tens of thousands of messages nobody reads are most of a rule's
    /// time.
    pub fn expect_with(
        &mut self,
        subject: impl Into<Subject>,
        holds: bool,
        detail: impl FnOnce() -> String,
    ) {
        self.expectations += 1;
        if !holds {
            self.failures.push(Failure {
                contract: self.contract.to_string(),
                subject: subject.into(),
                detail: detail(),
            });
        }
    }
}

/// One guarantee the driver must keep.
///
/// A rule is told once, when the run is complete -- after the test's inputs, the release rounds,
/// the close and the driver's exit -- and reads the whole recording through its views. It states
/// a property of the whole timeline, "the stream was still open when the speech completed", never
/// of the moment it happens to be read. A rule that only applies once the session has closed
/// reads [`Recording::phase`] and returns early otherwise.
pub trait Rule {
    /// What the rule promises, and the recordings that prove the promise can be checked.
    const CONTRACT: Contract;

    /// The run is complete: judge it.
    fn on_complete(r: &Recording, check: &mut Check);
}

/// What a rule promises, and how it proves it can tell.
///
/// The two lists stop a rule being decorative. Each `example` must be accepted *while making at
/// least one expectation*, so a rule that never applies fails its own registration. Each
/// `counterexample` must be rejected, so a rule that cannot fail is caught the day it is written.
/// A `probe` reaches the rule's prerequisite deterministically, and carries a whole [`Case`]
/// because some prerequisites are fixed when the session is built.
pub struct Contract {
    /// The rule's name in reports and the corpus: its file name.
    pub id: &'static str,
    /// The guarantee in one sentence, as a person would say it.
    pub guarantee: &'static str,
    pub examples: &'static [fn() -> Recording],
    pub counterexamples: &'static [fn() -> Recording],
    pub probe: Option<fn() -> Case>,
}

/// One rule as the registry holds it: its contract, and the function the complete run is handed
/// to. Generated by `build.rs` from `Rule::CONTRACT` and `Rule::on_complete` of each rule type.
pub struct Registered {
    pub contract: Contract,
    pub on_complete: fn(&Recording, &mut Check),
}

impl Registered {
    pub fn id(&self) -> &'static str {
        self.contract.id
    }

    pub fn run(&self, recording: &Recording) -> Check {
        let mut check = Check::new(self.contract.id);
        (self.on_complete)(recording, &mut check);
        check
    }
}

/// Run every contract over a finished recording.
///
/// Returns the failures and how many expectations each contract made, so a contract with zero is
/// reported as unexercised rather than quietly counted as a pass.
pub fn check_all(recording: &Recording) -> (Vec<Failure>, BTreeMap<&'static str, u32>) {
    let mut failures = Vec::new();
    let mut expectations = BTreeMap::new();
    for rule in rules::RULES {
        let check = rule.run(recording);
        *expectations.entry(rule.id()).or_default() += check.expectations;
        failures.extend(check.failures);
    }
    (failures, expectations)
}
