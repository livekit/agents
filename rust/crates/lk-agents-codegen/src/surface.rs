//! The whole `livekit.agents._core` surface: `_core.pyi`, which re-exports every name from the
//! generated stub that declares it, and `core_names.json`, the names `dir(_core)` returns, which
//! `lk-agents-py` compares with its registration table.

use crate::python::Out;

/// One generated `_core` stub module and the `_core` names it declares.
pub struct Stub {
    pub out: Out,
    pub names: Vec<String>,
}

/// The stub of the `_core` names still registered by handwritten pyo3 code, beside `_core.pyi`.
const HANDWRITTEN_STUB: &str = "_core_handwritten";

/// `_core` names registered by handwritten `#[pyclass]`/`#[pyfunction]` items (the export-placement
/// baseline) and stubbed in `_core_handwritten.pyi`. It only shrinks: a family moved to declarations
/// leaves it, and generation fails while a name is both here and generated.
const HANDWRITTEN: &[&str] = &[
    "AgentNodes",
    "ItemStream",
    "Role",
    "Run",
    "StreamReader",
    "Streams",
    "Thread",
    "Turn",
    "init",
    "resolve_host_ref",
    "stt_node",
    "tts_node",
];

/// `_core.pyi` (package-relative) and `core_names.json`, from the generated stubs of `_generated/`.
pub fn emit<'a>(stubs: impl IntoIterator<Item = &'a Stub>) -> Result<(Out, Out), String> {
    assemble(HANDWRITTEN, stubs)
}

fn assemble<'a>(
    handwritten: &[&'a str],
    stubs: impl IntoIterator<Item = &'a Stub>,
) -> Result<(Out, Out), String> {
    let mut modules: Vec<(String, Vec<&str>)> =
        vec![(format!(".{HANDWRITTEN_STUB}"), handwritten.to_vec())];
    for stub in stubs {
        let module = stub
            .out
            .path
            .strip_suffix(".pyi")
            .ok_or_else(|| format!("{}: a `_core` stub must be a `.pyi`", stub.out.path))?;
        modules.push((
            format!("._generated.{module}"),
            stub.names.iter().map(String::as_str).collect(),
        ));
    }
    let mut all: Vec<&str> = Vec::new();
    for (module, names) in &modules {
        for name in names {
            if all.contains(name) {
                return Err(format!(
                    "`_core.{name}` is declared twice (again in {module}); a family moved to \
                     declarations leaves `surface::HANDWRITTEN`"
                ));
            }
            all.push(name);
        }
    }
    modules.sort_by(|a, b| a.0.cmp(&b.0));

    let mut pyi = String::from(
        "# GENERATED FILE -- DO NOT EDIT.\n#\n# Written by `cargo run -p lk-agents-codegen -- --write` (in `rust/`): the stub of\n# `livekit.agents._core`, the pyo3 extension built from `rust/crates/lk-agents-py`. Every name\n# comes from the generated stub of its declaration, or from `_core_handwritten.pyi` while its\n# pyo3 code is still handwritten. `core_names.json` lists the same names.\n\n",
    );
    for (module, names) in &mut modules {
        if names.is_empty() {
            continue;
        }
        names.sort_by_key(|n| isort_key(n));
        pyi.push_str(&format!("from {module} import (\n"));
        for name in names.iter() {
            pyi.push_str(&format!("    {name} as {name},\n"));
        }
        pyi.push_str(")\n");
    }

    all.sort_unstable();
    // Names are identifiers: nothing to escape.
    let names: Vec<String> = all.iter().map(|n| format!("    \"{n}\"")).collect();
    let json = format!(
        "{{\n  \"about\": \"GENERATED by `cargo run -p lk-agents-codegen -- --write` (in `rust/`): every name dir(livekit.agents._core) returns that does not start with '__', sorted. lk-agents-py's export-table test asserts its registrations produce exactly this list.\",\n  \"names\": [\n{}\n  ]\n}}\n",
        names.join(",\n")
    );
    Ok((
        Out { path: "_core.pyi".to_owned(), text: pyi },
        Out { path: "core_names.json".to_owned(), text: json },
    ))
}

/// Ruff's isort order inside one `from` import: constants, then classes, then the rest, each
/// case-insensitively.
fn isort_key(name: &str) -> (u8, String) {
    let kind = if name.chars().any(char::is_uppercase) && !name.chars().any(char::is_lowercase) {
        0
    } else if name.starts_with(char::is_uppercase) {
        1
    } else {
        2
    };
    (kind, name.to_lowercase())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stub(path: &str, names: &[&str]) -> Stub {
        let names = names.iter().map(|n| n.to_string()).collect();
        Stub { out: Out { path: path.to_owned(), text: String::new() }, names }
    }

    #[test]
    fn every_name_is_re_exported_once_and_listed_sorted() {
        let stubs = [
            stub("_core_llm.pyi", &["Llm", "_core_chat"]),
            stub("_core_classes.pyi", &["END", "Abc"]),
        ];
        let (pyi, json) = assemble(&["init", "Role"], &stubs).expect("assembles");
        let pyi = pyi.text;
        assert!(
            pyi.contains(
                "from ._core_handwritten import (\n    Role as Role,\n    init as init,\n)"
            ),
            "{pyi}"
        );
        assert!(
            pyi.contains(
                "from ._generated._core_classes import (\n    END as END,\n    Abc as Abc,\n)"
            ),
            "{pyi}"
        );
        let listed: Vec<&str> =
            json.text.lines().filter_map(|l| l.strip_prefix("    \"")?.split('"').next()).collect();
        assert_eq!(listed, ["Abc", "END", "Llm", "Role", "_core_chat", "init"]);
    }

    // A family moved to declarations must leave the handwritten list, or `_core.pyi` would import
    // the name twice and the residue would never shrink.
    #[test]
    fn a_name_both_handwritten_and_generated_fails_generation() {
        let err =
            assemble(&["Judge"], &[stub("_core_classes.pyi", &["Judge"])]).err().expect("refused");
        assert!(err.contains("`_core.Judge` is declared twice"), "{err}");
    }
}
