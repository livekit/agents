import { compile } from 'json-schema-to-typescript';
import { readFile, writeFile, readdir } from 'node:fs/promises';
const dir = new URL('../src/lib/generated/', import.meta.url);
for (const name of await readdir(dir)) {
  if (!name.endsWith('.json')) continue;
  const schema = JSON.parse(await readFile(new URL(name, dir), 'utf8'));
  const content = await compile(schema, name.slice(0, -5), {
    bannerComment: '/* Generated by scripts/schemas.py + scripts/schemas.mjs from SDK schemas. Do not edit. */',
    unknownAny: true,
  });
  const target = new URL(name.replace('.json', '.ts'), dir);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Generated types drift: ${name}`);
  } else await writeFile(target, content);
}
