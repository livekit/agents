# The events a plugin's session emits and the generation it returns: Python objects (streams,
# futures, chat items) the session forwards to the core itself, so none is a core record.


@dataclass
class InputSpeechStartedEvent:
    pass


@dataclass
class InputSpeechStoppedEvent:
    user_transcription_enabled: bool


@dataclass
class MessageGeneration:
    message_id: str
    text_stream: AsyncIterable[str]  # could be io.TimedString
    audio_stream: AsyncIterable[rtc.AudioFrame]
    modalities: Awaitable[list[Literal["text", "audio"]]]


@dataclass
class GenerationCreatedEvent:
    message_stream: AsyncIterable[MessageGeneration]
    function_stream: AsyncIterable[FunctionCall]
    user_initiated: bool
    """True if the message was generated by the user using generate_reply()"""
    response_id: str | None = None
    """The response ID associated with this generation, used for metrics attribution"""


@dataclass
class InputTranscriptionCompleted:
    item_id: str
    """id of the item"""
    transcript: str
    """transcript of the input audio"""
    is_final: bool
    confidence: float | None = None
    """confidence score of the transcript (0.0 to 1.0), derived from model logprobs"""
    turn_started_at: float | None = None
    """When the turn this transcript belongs to began (``time.time()``).

    A provider that withholds the final transcript until its reply has finished
    generating should set this, so the user message can be placed on the session
    timeline where the turn happened rather than where the transcript arrived.
    """


@dataclass
class RealtimeSessionReconnectedEvent:
    pass


@dataclass
class RemoteItemAddedEvent:
    previous_item_id: str | None
    item: ChatItem


class RealtimeError(Exception):
    """Error raised by a realtime session when a request fails.

    Args:
        message: Human-readable description of the failure.
        code: Provider error code when the failure mirrors one (e.g. OpenAI's
            ``conversation_already_has_active_response``), so callers can branch on it
            programmatically; ``None`` when the error carries no provider code.
    """

    def __init__(self, message: str, *, code: str | None = None) -> None:
        super().__init__(message)
        self.code = code
